/**
 * 「这一句是不是人自己按的停」。
 *
 * **人按的停不是失败。** 引擎那头分得很清——`ref_gen.cpp` 里就写着
 * 「报成「出图失败：已取消」的话，人会去找哪儿出错了」——所以取消留下的
 * 话是「已取消」（大模型那条，`llm/client.cpp`）/「已停下这一张」
 * （出参考图那条）。而界面这边 `run()` 见到抛错一律弹红字，不分一下的话，
 * 自己按下去的停在屏幕上是一条红的报错。
 *
 * **判据只能是这句话。** 「停下」是从顶栏那块徽标按的（ThinkingBadge），
 * 而发请求的是另一个页面里的另一个函数，两边碰不着面；而且停也可能是
 * 从另一个标签页按的。
 *
 * 单开一个文件是因为它有三个互不相干的用处——`useAction` 的收尾（界面
 * 最底下那一层）、一键出图那圈的分支、故事页留不留那半截字（最上面那
 * 一层）——放进其中任何一个都会把另外两个拖进不该有的依赖里。
 */
export function stoppedByHand(message) {
  return /已停下|已取消/.test(message || '')
}
