/**
 * 「还没选项目」那一屏底下那句话。
 *
 * **一个项目都没有的时候，"在项目库里点一个"是句办不到的话。** 四页各写
 * 各的：项目页写的是「在项目库那条栏里点一个，**或者点栏头的加号建一个**」，
 * 而故事 / 设定 / 这一集三页只写了前半句。装好之后第一次打开，项目库那条栏
 * 是空的，这三页却在叫人去那儿点一个——一台新机器上最先撞见的就是这句。
 *
 * （初始化那一页 2026-09-14 删了，所以"第一次打开该干什么"现在全靠这句话。）
 *
 * 收成一处而不是四处各判一次：判据只有一条，散开就会有人漏掉。
 *
 * @param {{loaded: boolean, count: number}} projects `useProjects()`
 */
export function pickProjectHint(projects) {
  // 还没读回来：别抢着说"一个都没有"。读的那一下屏幕上本来就有别的动静。
  if (!projects?.loaded) return '在项目库那条栏里点一个'
  return projects.count
    ? '在项目库那条栏里点一个'
    : '还一个项目都没有。点项目库栏头的加号建一个'
}
