#pragma once

// 从已有剧集反推一份故事骨架。
//
// **老项目接不上新流程**，这是迁移里最后一条空着的路（见
// docs/故事优先重构方案.md 第六节）。老项目手里有的是一集集写好的剧本，
// 没有 story.json；于是人物关系、地点、全局记忆这些新做的东西它一样都用
// 不上，往下写第六集照样失忆。
//
// **这一步不碰大模型。** 反推出来的是骨架：每一集变成一章，正文就是那一
// 集的剧本原文，段落边界登记成候选切点。谁是谁、什么关系、在哪儿，交给
// 已经有的「读现成正文提结构」（stages/story_analyze）——那一步才要模型。
// 分成两步不是省事：骨架这一半是机械的、可重复的，混进模型调用之后就没
// 法说「重来一次得到的还是同一份」了。
//
// **反推出来的故事不重新分集。** 老项目那几集已经排了分镜、出了片，按时长
// 重切会让所有集的边界挪位，而边界一挪，已经渲染好的镜头就对不上它该在的
// 那一段了。所以分集表是照着现有剧集一比一列出来的：一集一章，整章。
// 想重切是之后改每集时长时的事，那时用户自己按一次。

#include "models/project.hpp"
#include "models/story.hpp"

namespace changji::stages {

/// 照着项目里已有的剧集反推一份故事。
///
/// 只收**写了剧本**的那些集：没剧本的集反推出来是一章空正文，既提不出结构
/// 也切不出分集，只会在章节列表里占一行说不清的东西。
///
/// 章的顺序就是剧集的顺序，章 id 重新从 ch01 排——**不照搬 episode_id**。
/// 老项目里的集号可能是 ep01/ep03/ep07（删过几集），而章 id 要求
/// `^ch[0-9]+$` 且在故事里连续。分集表那一条仍然指回真正的 episode_id，
/// 两边靠它对上。
models::Story story_from_episodes(const models::Project& project);

}  // namespace changji::stages
