// 逐章展开正文的提示词。**这个文件就是出处，直接改它。**
// 新写的，不受逐字节约束。
//
// 这一步补的是 AI 那条路上最后一个洞：大纲写出来的故事**只有梗概没有正文**，
// 写剧本时展开的是「这一章发生什么，三五句」，而不是真正的内容。
//
// ---- 2026-09-12 重写：从「一堆段落」改成「几场戏」----
//
// 上一版的产物用户的判词是「只能叫剧本不能叫故事/小说」。实测那一章
// （chapter_check8 / ch02，1674 字）把重逢、决裂、离开、回来、和好五件事
// 全写完了，每一段推进一整个事件——叙事学上这叫**概述**（叙述时长远短于
// 故事时间）。小说读起来是小说靠的是**场景**：叙述时长约等于故事时间，
// 一个动作一段、一句对白一段。
//
// 上一版的三条规则直接造出了这个结果：
//   · schema 里写着「一段一两句话、三四十个字」+ 段数 = 字数/35
//     → 数学上就规定了每段 35 字的字幕体；
//   · 「不要写替读者解释心理和意义的旁白」→ 模型理解成「不许写内心」，
//     于是只剩「神情复杂」「心中涌起难以言喻的情绪」这类情绪标签；
//   · 「不要描写长相、发型、服装」→ 扩大成「不要描写人」，人物在场上没有身体。
// 而提示词里从头到尾没有「场」这个单位，模型拿到整章梗概只能平摊。
//
// 现在：一章 = 几场戏，一场 = 一个地方一段时间里，谁想干什么、谁拦着、
// 最后局面变成什么（turn）。turn 就是那一集的收口——**分集从此按场切，
// 不再靠模型抄一句原文回来定位**。
//
// 拼接顺序：Seg0 + 画风 + Seg1 + 场数 + Seg1b + 每场字数 + Seg2 + Rules
//           + ContextHead + 上下文 + Tail
//
// ---- 2026-09-12 晚：25 条砍成 8 条 ----
//
// 规则一条条加上去，加到 25 条、两千两百字，排在故事内容前面。用户贴回来
// 一段实际输出才看清代价：**模型在输出里一条条核对规则**（「Wait, rule 23
// says last line is the turn moment」），还把思考编成字段名塞进 JSON。
// 详见 kChapterRules 后面那段注释。砍掉的三类：教它凑字数的、给配额的、
// 和 schema/守卫重复的。
//
// ⚠️ 更早那条记录：第 7 条（不靠眼睛的细节）的下限曾从「至少一个」提到
// 「三四处」，**那一轮的对照是无效的**——同一天机器上的模型也从
// Qwen3-14B 换成了 32B（配置 14:52 改的，对照两跑一个 14:27 一个 15:03）。
// 那条配额现在连同规则一起砍了，理由是配额会变成填配额。

