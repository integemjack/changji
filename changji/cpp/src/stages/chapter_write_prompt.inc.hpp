inline constexpr const char* kChapterRules =
    R"CJ(
1. **写场面，不写概述。这一条最要紧。** 一段推进的是一两秒钟的事：一个
   动作、一句话、一次看见。一段吃掉一整件事（谁转身走了、谁想通了、
   两人和好了），那是梗概不是正文。
2. 【这一章】里的事不止一件。**挑最要紧的几件，一件一场，实时地写**，
   剩下的用一两句推过去。每一场开头先落地：在哪、什么光、谁在、
   手上正在做什么。一场里的时间是连着的，要跳过半小时那就是下一场。
3. **一场只跟着一个人走。** pov 那个人心里想什么可以写；别人心里想什么
   一个字都不能写，只能从外面看见。内心写成身体，和他此刻真在想的那件
   具体的事——别写成情绪的名字。
4. **具体。** 不说「一件信物」，说「一枚缺了角的铜钱」。别堆形容词，
   一个准确的名词加一个准确的动词顶十个。场面里不能全是眼睛看见的东西，
   也要有听见的、闻到的、摸到的。
5. **不要写长相、发型、服装的款式和颜色**——那由后面的美术那一步统一定，
   这里写了两边必然对不上。但身体要在场上：手在干什么、隔多远、声音哑
   不哑、衣服湿没湿。
6. **对白一来一往。** 说话的人用人物表里的名字，别写「有人说」「那边传来
   熟悉的声音」。不用每句都「某某说」，可以先给个动作再开口。
   **话里要留东西**——答非所问、说半句、扯到别处，都比说破了更像真人。
   留的是什么，看人物表里「他怕的是」那一条。
7. **只写这一章**，从上一章停下的地方接着走。后面的事一个字都不要提前写，
   前情提要里的事不重演。人物名和下面给的一字不差。【地方】那一份是整个
   故事的清单不是这一章的，用得着哪一两个就只写哪一两个。
   人物表里写了每个人「会从什么变成什么」，**那个变化要写成行为**：
   同一种处境下他这次的选择和上次相反，别让谁开口说自己变了。
8. **每一场停在它的 turn 上**，而且要悬着：一个新麻烦、一句收不回来的话、
   一样刚被看见的东西。把事情了结掉的（想通了、放下了、释然了）不是 turn。
   turn 必须拍得出来，脑子里的事镜头拍不到。最后那一下单独填进 last_line。

)CJ";

