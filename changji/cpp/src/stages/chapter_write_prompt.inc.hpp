//
// 2026-09-12 用户贴回来一段实际输出，里面有这么一行：
//     Wait, rule 23 says last line is the turn moment. So paragraphs go
// 还有一串它自己造的"字段名"当思考草稿：
//     last_line_ending_context_hint_for_model_only_not_outputted_but_used_to…
//     turn_description_internal_note_do_not_output_as_text_field_value_directly…
// 最后垮成一串没完没了的下划线词表（…facsimile_scan_snapshot_photo…）。
//
// Qwen3.8 这类带推理的模型，思考被 <think></think> 堵住之后并没有消失，
// **只是没地方放**；而 GBNF 只允许它输出 JSON，于是思考被挤进字段名和
// 字符串里。再给它一份 25 条、两千两百字的检查清单，它就一条条核对给你看。
//
// 这一版砍到 8 条（约八百字），砍掉的是：
// · 「写短了就回去把那场戏演完整」——**那是在明着教它凑字数**，
//   而用户的判词正是"好多明显是凑字数的字符"；
// · 「不靠眼睛的细节一场里要有三四处」——配额会变成填配额，
//   实测"体感套话"（他感到一阵…、指节泛白）正是涨得最多的一项；
// · 十一个禁用词的清单——反例句会被原样抄走（这个坑记过），
//   而情绪标签本来就有守卫在拦，不必在提示词里再念一遍；
// · 和 schema / 守卫重复的那几条（对白用双引号、不许写镜头、
//   同一句不许出现两次、每场都要有人说话、两场不能撞车）——
//   它们都已经有硬约束或就地修补在管，写进提示词只是多占注意力。

// 第一章没有前情、没有上一章的结尾，提示词短一大截，实跑时 14B 两次都只写出
// 一百来个字。给它一个明确的起点，别让那个位置空着。
inline constexpr const char* kChapterFirstHead =
    R"CJ(
【这是第一章】故事从这儿开始，**读者对这些人一无所知**。
· 第一场直接进场面：在哪、谁在、正在做什么。不写题记、不写引言。
· **开头几段之内就要有人开口。** 实测第一章的对白总是全书最少的——
  没有前情可接，模型就一个人在那儿看和想。而读者认人靠的是听他们说话，
  一整章只有叙述，人物立不起来。
· **谁是谁、谁和谁什么关系，靠他们怎么称呼对方、怎么接话带出来**，
  不要用一句叙述挑明（「谁和谁曾经是什么」那种句子）——那种句子一出现，
  读者就从戏里被拎出来了。
)CJ";

