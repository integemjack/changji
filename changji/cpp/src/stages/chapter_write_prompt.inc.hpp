inline constexpr const char* kChapterRules =
    R"CJ(
**一、写场面，不写概述。这一条是全部里最要紧的。**
1. 一段推进的是**一两秒钟的事**：一个动作、一句话、一次看见、一个念头。
   一段吃掉一整件事（谁转身走了、谁想通了、两人和好了），那是梗概不是正文。
2. 下面【这一章】里写的事不止一件。**挑最要紧的几件，一件一场，实时地写**；
   剩下的用一两句话推过去。不要一件事一段，把整章摊成一串镜头。
3. 每一场开头先落地：在哪、什么时候、什么光、谁在场、手上正在做什么。
4. 一场里的时间是连着的。中间要跳过半小时，那就是下一场了。

**二、一场只跟着一个人走。**
5. pov 那个人心里想什么可以写；**别人心里想什么一个字都不能写**，
   只能从外面看见——他做了什么、说了什么、脸转向哪儿。一场里进两个人的
   脑子，读者立刻出戏。
6. 内心不要写成情绪的名字，写成身体，和他此刻真在想的那件具体的事。
   下面这些词一个都不要用：神情复杂、五味杂陈、百感交集、难以言喻、
   若有所思、不知所措、心中涌起、内心充满、眼中满是、久久不能平静、
   意味深长。它们替读者把感受做完了，读者就没什么可感受的。

**三、看得见、听得见、摸得着。**
7. 每一场至少要有一个**不靠眼睛**的细节：一个声音、一股味道、一个温度、
   一下触感。全是视觉的场面是空的。
8. 东西要具体到看得见：不说「一件信物」，说「一枚缺了角的铜钱」。
   地方也一样，写出这一处独有的那样东西。
9. 别堆形容词。一个准确的名词加一个准确的动词，顶十个形容词。
10. **不要写长相、发型、服装的款式和颜色**——人物长什么样由后面的美术那
   一步统一定，这里写了两边必然对不上。
   但**身体要在场上**：手在干什么、隔多远、声音哑不哑、衣服湿没湿、
   坐着还是站起来了。这一条不是让你别写人，是别定他长什么样。

**四、对白。**
11. 对白用 “” 双引号，谁说的和说了什么放在同一段。
    **说话的人要有名字**，就是人物表里那个名字。不要写成「那边传来熟悉的
    声音」「有人说」——读者认不出是谁在说话，后面写剧本那一步也认不出，
    那句台词会变成没有主人的旁白。
12. 不要每一句都「某某说」。用动作把话带出来：他先做了个什么动作，再开口。
13. 话里要留东西。人不会把心里的事说全——答非所问、说半句、扯到别处，
   都比说破了更像真人。
14. 一来一往地写。连着好几段只有一个人在说，画面就停住了。

**五、只写这一章。**
15. 后面几章的事一个字都不要提前写。前情提要里的事都已经发生过，不重演。
16. 从上一章停下的地方接着走。
17. **下面【地方】那一份是整个故事的清单，不是这一章的。** 这一章用得着
   哪一两个地方，就只写那一两个——一章里的几场戏本来就该发生在同一个地方
   或者隔壁，跑遍全城的每一个地点，说明是在拿地点凑场数。
18. 人物名和下面给的一字不差，不要冒出没在人物表里的人。
19. 同一句话、同一个动作，一章里不要出现第二次。
20. **每一场都要有人说话，一场也不能少。** 一个人从头想到尾、一句对白
   都没有的场，切出来就是一集默片。场上只有一个人的时候，要么让另一个人
   进来，要么把这一场换成有人在的地方——回忆不是戏。
21. **两场不能停在同一件事上。** 每一场的 turn 各是一集的钩子，两集钩子
   撞车，观众看到的是剧情在原地打转。上一章已经停过的地方也不能再停一次。

**六、每一场停在它的 turn 上。**
22. turn 是这一场结束时**局面变成了什么**，而且要悬着：一个新麻烦、
   一句收不回来的话、一样刚被看见的东西。把事情了结掉的（和好了、
   想通了、放下了、释然了）不是 turn。
23. 每一场的**最后一段就落在这个 turn 上**：一句话，一行。
   **后面不要再加一段来点题。** 最后一段里不要出现「终于」「从此」
   「明白了」「放下了」「释然」这类收束的说法——它们一出现，
   悬念当场就被填平了。
24. turn 那一栏写的是**这件事的说法**，不是让你抄进正文的句子。
   用一个动作、一句台词把它写出来，别把那行字原样搬进 paragraphs。
25. **每一场的末尾就是一集的收口**：这一章会按场切成集，
   所以每一场都得值得当一集的结尾。

)CJ";

