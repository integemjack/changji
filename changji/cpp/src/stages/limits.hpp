#pragma once

// 视频模型的硬限制。
//
// **单独一个头文件，因为三个阶段都要用它，而且必须是同一份。**
//
// 分镜要按它推时长档位，渲染要按它算帧数，配音要按它判一句台词能不能
// 装进一个镜头。之前 storyboard.hpp 和 render.hpp 各写了一份
// `kMaxFrames`——两份值碰巧一样，所以一直没出事，但那是运气：
// 任何一个文件同时包含这两个头就是重定义错误，而只改一边则是
// "分镜按 5 秒排，渲染按 8 秒截"这种谁也发现不了的不一致。

namespace changji::stages {

/// Wan 单段能生成的最大帧数。
///
/// 超过这个数会在约 100 帧处到达末帧然后往回跑，出现乒乓现象。
/// **这是模型本身的限制，不是可调参数。**
inline constexpr int kMaxFrames = 121;

/// 单个镜头能生成的最长时长。
///
/// **分镜的时长档位必须由它推导，不能各写一份。** 早先档位表里有 8 秒和
/// 10 秒，而实际上限是 5 秒，多出来的部分被静默截断，
/// 成片比计划短了一大截且没人发现。
double max_shot_duration_s(int fps = 24);

}  // namespace changji::stages
